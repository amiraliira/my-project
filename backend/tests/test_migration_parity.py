"""Reference bytes generated locally by the deployed .NET 10 runtime."""
from decimal import Decimal, localcontext
import hashlib
from pathlib import Path
import unittest
from unittest.mock import patch

from pak_maintenance.common import loads, ApiError
from pak_maintenance.pm_hash_json import canonical_json
from pak_maintenance.work_service import WorkService
from test_api import Fixture

REFERENCE = Path(__file__).parent / "serializer_reference" / "dotnet-serializer.json"


class SerializerParityTests(unittest.TestCase):
    def test_real_dotnet_ascii_persian_html_emoji_and_decimal_bytes(self):
        data = loads(REFERENCE.read_text(encoding="utf-8-sig"))
        self.assertEqual(data["framework"], ".NET 10.0.12")
        self.assertEqual(canonical_json(data["ascii"]), data["asciiJson"])
        self.assertEqual(canonical_json(data["payload"]), data["json"])
        self.assertEqual(hashlib.sha256(canonical_json(data["payload"]).encode()).hexdigest().upper(), data["sha256"])
        with localcontext() as context:
            context.prec = 5
            for case in data["decimals"]:
                with self.subTest(input=case["input"]):
                    self.assertEqual(canonical_json(Decimal(case["input"])), case["json"])


class ExistingClaimReplayTests(Fixture):
    def setUp(self):
        super().setUp()
        from pak_maintenance.common import User
        self.user = User("tech", "tech", "تکنسین", "technician", "برق")
        with self.db.transaction() as c:
            c.execute("INSERT INTO users(id,code,name,role,specialty,active,password_hash,session_epoch) VALUES('tech','tech','تکنسین','technician','برق',1,'',0)")
            c.execute("INSERT INTO assets(id,code,name,hall,line,body,version) VALUES('asset','A01','پمپ','فرایند','خط یک','{}',1)")
            c.execute("INSERT INTO parts(id,code,name,specification,unit,version) VALUES('part','P01','قطعه','','عدد',1)")

    def test_old_csharp_hash_replays_same_document_without_duplicate(self):
        data = loads(REFERENCE.read_text(encoding="utf-8-sig"))
        work = WorkService(self.db)
        result = work.save(self.user, data["payload"])
        # A historical claim contains the actual digest generated by C#.
        with self.db.transaction() as c:
            c.execute("INSERT INTO request_claims(actor_id,request_key,order_id,payload_hash) VALUES('tech','old-csharp-key',:id,:hash)", {"id": result["id"], "hash": data["sha256"]})
        replay = work.save(self.user, data["payload"], request_key="old-csharp-key")
        self.assertEqual(replay["id"], result["id"])
        with self.db.connect() as c:
            self.assertEqual(c.scalar("SELECT COUNT(*) FROM orders"), 1)

    def test_revoked_actor_cannot_mutate_after_old_request_snapshot(self):
        data = loads(REFERENCE.read_text(encoding="utf-8-sig"))
        with self.db.transaction() as c:
            c.execute("UPDATE users SET active=0,session_epoch=1 WHERE id='tech'")
        with self.assertRaises(ApiError):
            WorkService(self.db).save(self.user, data["payload"])
        with self.db.connect() as c:
            self.assertEqual(c.scalar("SELECT COUNT(*) FROM orders"), 0)


if __name__ == "__main__":
    unittest.main()
